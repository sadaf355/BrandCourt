"""Deterministic privacy, language, declaration and tone checks for BrandCourt.
These are explainable heuristics; they are not a general-purpose language model.
"""
from __future__ import annotations
import re

EMAIL = re.compile(r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", re.I)
PHONE = re.compile(r"(?<!\w)(?:\+?91[\s-]?)?[6-9]\d{9}(?!\w)")
AADHAAR = re.compile(r"(?<!\d)\d{4}[ -]?\d{4}[ -]?\d{4}(?!\d)")
SECRET = re.compile(r"\b(?:api[_ -]?key|access[_ -]?token|password)\s*[:=]\s*[^\s,;]+", re.I)

def mask_sensitive(text: str) -> tuple[str, int]:
    """Mask obvious PII/secrets before any optional model call."""
    count = 0
    for pattern, replacement in ((EMAIL, "[MASKED_EMAIL]"), (PHONE, "[MASKED_PHONE]"), (AADHAAR, "[MASKED_ID]"), (SECRET, "[MASKED_SECRET]")):
        text, n = pattern.subn(replacement, text)
        count += n
    return text, count

def detect_language(text: str) -> dict:
    devanagari = len(re.findall(r"[\u0900-\u097F]", text))
    latin = len(re.findall(r"[A-Za-z]", text))
    words = set(re.findall(r"[a-z]+", text.lower()))
    hindi_roman = {"hai", "hain", "kya", "aap", "mera", "meri", "ke", "liye", "bahut", "accha", "achha", "nahi", "nahin", "kaise", "kar", "karo", "se", "mein", "par"}
    roman_hit = len(words & hindi_roman)
    if devanagari and latin and roman_hit >= 2:
        language, support = "hinglish", "limited"
    elif devanagari:
        # Devanagari is shared by Hindi and Marathi; Marathi lexicon only provides a hint.
        mr = {"आहे", "आणि", "नाही", "माझा", "माझी", "करा", "तुम्ही", "साठी", "होते"}
        language = "mr" if any(w in text for w in mr) else "hi"
        support = "limited" if language == "mr" else "supported"
    elif latin and roman_hit >= 2:
        language, support = "hinglish", "limited"
    elif latin:
        language, support = "en", "supported"
    else:
        language, support = "unknown", "limited"
    return {"language": language, "support": support, "method": "script_and_lexicon_heuristic"}

PAID_CHANNELS = {"paid_ad", "instagram", "facebook", "linkedin"}
PAID_LABELS = ("#ad", "#sponsored", "paid partnership", "paid promotion", "gifted", "advertisement", "sponsored by")
AI_LABELS = ("ai-generated", "ai generated", "made with ai", "synthetic media", "generated by ai", "#aigenerated")
FACTUAL_MARKERS = re.compile(r"\b(\d+(?:\.\d+)?\s*(?:%|percent|days?|weeks?|months?|years?|hours?)|clinically proven|dermatologist tested|tested by|reduces|improves|increases|decreases|contains)\b", re.I)
ABSOLUTES = re.compile(r"\b(always|never|guaranteed|100%|zero risk|no side effects|permanent results)\b", re.I)

def layer1_checks(text: str, channel: str, alt_text: str | None = None, is_ai_media: bool = False) -> list[dict]:
    lower = text.lower()
    findings: list[dict] = []
    if channel == "paid_ad" or (channel in PAID_CHANNELS and re.search(r"\b(ad|sponsored|paid partnership|gifted)\b", lower)):
        if not any(label in lower for label in PAID_LABELS):
            findings.append({"code":"IN-4", "type":"missing_disclosure", "severity":"critical", "verdict":"unsupported", "message":"Paid or gifted content should have a clear disclosure such as #ad or Paid partnership. Confirm the applicable platform and rules."})
    if is_ai_media and not any(label in lower for label in AI_LABELS):
        findings.append({"code":"IN-6", "type":"ai_disclosure_reminder", "severity":"warning", "verdict":"needs_human_review", "message":"AI-generated or synthetic media may require a platform disclosure. Advisory reminder only; check the platform's current policy."})
    if not (alt_text or "").strip():
        findings.append({"code":"A11Y-ALT", "type":"missing_alt_text", "severity":"warning", "verdict":"needs_human_review", "message":"No image alt text is recorded. Add concise, meaningful alternative text for informative imagery."})
    if FACTUAL_MARKERS.search(text) and not re.search(r"\b(source|terms apply|results may vary|according to|study|report)\b", lower):
        findings.append({"code":"IN-1", "type":"substantiation_reminder", "severity":"warning", "verdict":"needs_human_review", "message":"A factual or performance claim may need a traceable source. No source language was detected; this is a reminder, not a factual determination."})
    if re.search(r"\b(disclaimer|terms apply|results may vary)\b", lower) and ABSOLUTES.search(text):
        findings.append({"code":"IN-3", "type":"disclaimer_conflict", "severity":"critical", "verdict":"needs_human_review", "message":"Absolute wording appears alongside disclaimer language. A disclaimer does not necessarily cure a misleading main claim; human review required."})
    return findings

def advisory_tone(text: str) -> list[dict]:
    flags=[]
    if ABSOLUTES.search(text):
        flags.append({"code":"TONE-ABSOLUTE", "severity":"advisory", "message":"Absolute or guaranteed language detected; verify it is supportable and on-brand."})
    if text.count("!") >= 3 or text.isupper() and len(text) > 20:
        flags.append({"code":"TONE-INTENSITY", "severity":"advisory", "message":"High-intensity punctuation or all-caps wording may conflict with a calm brand voice."})
    return flags
